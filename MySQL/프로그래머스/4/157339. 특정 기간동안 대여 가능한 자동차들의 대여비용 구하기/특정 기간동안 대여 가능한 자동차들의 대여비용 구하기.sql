SELECT r.CAR_ID,
        r.CAR_TYPE, 
        ROUND(r.DAILY_FEE * (100 - p.DISCOUNT_RATE) * 30 / 100) AS `FEE`
FROM CAR_RENTAL_COMPANY_CAR r
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN p
    ON r.CAR_TYPE = p.CAR_TYPE
WHERE r.CAR_TYPE IN ('세단', 'SUV')
    AND p.DURATION_TYPE = '30일 이상'
    AND NOT EXISTS (
        SELECT 1
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY h
        WHERE h.CAR_ID = r.CAR_ID
            AND '2022-11-01' BETWEEN h.START_DATE AND h.END_DATE
    )
HAVING FEE >= 500000
    AND FEE < 2000000
ORDER BY FEE DESC, r.CAR_TYPE ASC, r.CAR_ID DESC;
